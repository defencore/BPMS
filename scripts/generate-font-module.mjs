import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const regular = readFileSync(join(root, 'assets/fonts/DejaVuSans.ttf')).toString('base64');
const bold = readFileSync(join(root, 'assets/fonts/DejaVuSans-Bold.ttf')).toString('base64');
const output = join(root, 'src/vendor/dejavu-font-data.js');
const source = `// Generated by scripts/generate-font-module.mjs. Do not edit manually.\nexport const DEJAVU_SANS_REGULAR = '${regular}';\nexport const DEJAVU_SANS_BOLD = '${bold}';\n`;
writeFileSync(output, source);
console.log(`Generated ${output}`);
